let hasilCopy = "";


// ========================================
// AMBIL DATA ACAK
// ========================================

function ambilAcak(data) {

    if (!Array.isArray(data) || data.length === 0) {
        return "";
    }

    return data[Math.floor(Math.random() * data.length)];

}


// ========================================
// COPY TEKS
// ========================================

async function copyTeks(text, button) {

    if (!text) return;

    try {

        await navigator.clipboard.writeText(text);

    } catch (error) {

        const textarea = document.createElement("textarea");

        textarea.value = text;

        textarea.style.position = "fixed";
        textarea.style.left = "-9999px";

        document.body.appendChild(textarea);

        textarea.focus();
        textarea.select();

        try {

            document.execCommand("copy");

        } catch (e) {

            console.log("Copy gagal:", e);

        }

        textarea.remove();

    }


    if (button) {

        const teksAwal = button.innerHTML;

        button.innerHTML = "COPIED ✔";

        button.disabled = true;

        setTimeout(() => {

            button.innerHTML = teksAwal;

            button.disabled = false;

        }, 1500);

    }

}


// ========================================
// SARAN GAME
// ========================================

function saranGame(id, button) {

    const game = dataGame[id];

    if (!game) {

        console.log("Game tidak ditemukan:", id);

        return;

    }

    hasilCopy = ambilAcak(game.saran);

    copyTeks(hasilCopy, button);

}


// ========================================
// POLA GAME
// ========================================

function polaGame(id, button) {

    const game = dataGame[id];

    if (!game) {

        console.log("Game tidak ditemukan:", id);

        return;

    }

    hasilCopy = ambilAcak(game.pola);

    copyTeks(hasilCopy, button);

}


