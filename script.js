let hasilCopy = "";


function ambilAcak(data){

    return data[Math.floor(Math.random()*data.length)];

}


function saranGame(id){

    const game = dataGame[id];

    if(!game) return;

    hasilCopy = ambilAcak(game.saran);

    copyTeks();

}


async function copyTeks(){

    try{

        await navigator.clipboard.writeText(hasilCopy);

    }

    catch(error){

        console.log("Copy teks gagal");

    }

}


async function copyGameImage(id){

    const img = document.querySelector(
        ".game-box:nth-child("+id+") img"
    );

    if(!img){

        console.log("Foto tidak ditemukan");

        return;

    }

    try{

        const canvas = document.createElement("canvas");

        const ctx = canvas.getContext("2d");

        const image = new Image();

        image.src = img.src;

        image.onload = async function(){

            canvas.width = image.naturalWidth;

            canvas.height = image.naturalHeight;

            ctx.drawImage(
                image,
                0,
                0
            );

            canvas.toBlob(async function(blob){

                await navigator.clipboard.write([

                    new ClipboardItem({

                        "image/png":blob

                    })

                ]);

            },"image/png");

        };

    }

    catch(error){

        console.log("Copy gambar gagal",error);

    }

}


