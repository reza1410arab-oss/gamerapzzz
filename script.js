document.addEventListener("DOMContentLoaded", function () {

    const container = document.getElementById("gameContainer");

    if (!container) {

        console.log("ERROR: gameContainer tidak ditemukan!");

        return;

    }


    container.innerHTML = "";


    for (let i = 1; i <= 36; i++) {

        const game = dataGame[i];

        if (!game) continue;


        const gameBox = document.createElement("article");

        gameBox.className = "game-box";


        gameBox.innerHTML = `

            <div class="image-wrapper">

                <img
                    src="img/game${i}.jpg"
                    alt="${game.nama}"
                    loading="lazy"
                >

            </div>

            <div class="game-title">
                ${game.nama}
            </div>

            <div class="button-group">

                <button
                    class="btn btn-saran"
                    onclick="saranGame(${i}, this)"
                >
                    🎯 SARAN GAME
                </button>

                <button
                    class="btn btn-pola"
                    onclick="polaGame(${i}, this)"
                >
                    🔥 POLA GAME
                </button>

            </div>

        `;


        const img = gameBox.querySelector("img");

        img.addEventListener("error", function () {

            console.log(
                "❌ Foto tidak ditemukan: img/game" + i + ".jpg"
            );

        });


        img.addEventListener("load", function () {

            console.log(
                "✅ Foto berhasil dimuat: game" + i + ".jpg"
            );

        });


        container.appendChild(gameBox);

    }

});
